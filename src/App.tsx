export interface RenderLetterMapping {
  char: string;
  from: { x: number; y: number; char: string; index: number };
  to: { x: number; y: number; char: string; index: number };
  order: number;
}

interface Glyph {
  char: string;
  letter: boolean;
  x: number;
  y: number;
  w: number;
  index: number;
}

function clamp(x: number, a = 0, b = 1): number {
  return Math.max(a, Math.min(b, x));
}

function smoother(t: number): number {
  t = clamp(t);
  return t * t * t * (t * (t * 6 - 15) + 10);
}

function seed01(n: number): number {
  const x = Math.sin(n * 127.1 + 311.7) * 43758.5453123;
  return x - Math.floor(x);
}

export function computeLetterTransform(
  m: RenderLetterMapping,
  normT: number,
  _motionStyle: MotionStyle = 'arc',
  w: number,
  h: number,
  _totalLetters: number = 16
): { x: number; y: number; rotation: number; scale: number; local: number } {
  const local = smoother(normT);
  let x = m.from.x + (m.to.x - m.from.x) * local;
  let y = m.from.y + (m.to.y - m.from.y) * local;
  const scale = 1;

  const dir = seed01(m.order * 19) > 0.5 ? 1 : -1;
  const height = (h * 0.22) + seed01(m.order * 37) * (h * 0.28);
  y -= Math.sin(normT * Math.PI) * height;
  x += Math.sin(normT * Math.PI) * dir * (12 + seed01(m.order * 7) * 26);
  const rotation = Math.sin(normT * Math.PI) * (dir * 0.35);

  return { x, y, rotation, scale, local };
}

function fitFontSize(ctx: CanvasRenderingContext2D, text: string, maxWidth: number, start = 54): number {
  let size = start;
  while (size > 16) {
    ctx.font = `bold ${size}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;
    if (ctx.measureText(text).width <= maxWidth) break;
    size -= 2;
  }
  return size;
}

function computeGlyphLayout(ctx: CanvasRenderingContext2D, text: string, y: number, fontSize: number, canvasWidth: number): Glyph[] {
  ctx.font = `bold ${fontSize}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;
  const chars = [...text];
  const widths = chars.map(ch => ctx.measureText(ch).width);
  const totalWidth = widths.reduce((a, b) => a + b, 0);

  let cursor = canvasWidth / 2 - totalWidth / 2;
  const glyphs: Glyph[] = [];

  chars.forEach((ch, i) => {
    const w = widths[i];
    glyphs.push({
      char: ch,
      letter: /[A-Za-z]/.test(ch),
      x: cursor + w / 2,
      y,
      w,
      index: i,
    });
    cursor += w;
  });

  return glyphs;
}

export function buildLetterMapping(
  ctx: CanvasRenderingContext2D,
  from: string,
  to: string,
  canvasWidth: number,
  canvasHeight: number
): { mapping: RenderLetterMapping[]; src: Glyph[]; dst: Glyph[]; fontSize: number } {
  const maxW = canvasWidth - 80;
  const sizeFrom = fitFontSize(ctx, from, maxW, Math.min(54, Math.floor(canvasHeight * 0.16)));
  const sizeTo = fitFontSize(ctx, to, maxW, Math.min(54, Math.floor(canvasHeight * 0.16)));
  const fontSize = Math.min(sizeFrom, sizeTo);

  const centerY = canvasHeight / 2;
  const src = computeGlyphLayout(ctx, from, centerY, fontSize, canvasWidth);
  const dst = computeGlyphLayout(ctx, to, centerY, fontSize, canvasWidth);

  const buckets: Record<string, Glyph[]> = {};
  src.forEach(g => {
    if (!g.letter) return;
    const k = g.char.toLowerCase();
    if (!buckets[k]) buckets[k] = [];
    buckets[k].push(g);
  });

  const mapping: RenderLetterMapping[] = [];
  const used: Record<string, number> = {};

  dst.forEach(g => {
    if (!g.letter) return;
    const k = g.char.toLowerCase();
    const n = used[k] || 0;
    const s = (buckets[k] || [])[n];
    used[k] = n + 1;
    if (s) {
      mapping.push({
        char: g.char,
        from: { x: s.x, y: s.y, char: s.char, index: s.index },
        to: { x: g.x, y: g.y, char: g.char, index: g.index },
        order: mapping.length,
      });
    }
  });

  return { mapping, src, dst, fontSize };
}

export function renderRearrangementCanvas(
  progress: number,
  canvas: HTMLCanvasElement,
  source: string,
  target: string,
  motionStyle: MotionStyle = 'arc'
) {
  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  const w = canvas.width;
  const h = canvas.height;

  // Background
  ctx.fillStyle = '#09090b';
  ctx.fillRect(0, 0, w, h);

  const from = source.trim();
  const to = target.trim();

  if (!from || !to || !exact(from, to)) {
    ctx.fillStyle = '#71717a';
    ctx.font = `500 ${Math.max(14, Math.floor(h * 0.05))}px ui-monospace, SFMono-Regular, Menlo, monospace`;
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';
    ctx.fillText('Select an exact anagram to animate', w / 2, h / 2);
    return;
  }

  const { mapping, src, dst, fontSize } = buildLetterMapping(ctx, from, to, w, h);
  const holdStart = 0.12;
  const moveEnd = 0.85;

  ctx.font = `bold ${fontSize}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;

  // Draw static punctuation
  const drawPunctuation = (glyphs: Glyph[], alpha: number) => {
    ctx.save();
    ctx.fillStyle = '#f4f4f5';
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';
    ctx.globalAlpha = alpha;
    for (const g of glyphs) {
      if (!g.letter && g.char.trim()) {
        ctx.fillText(g.char, g.x, g.y);
      }
    }
    ctx.restore();
  };

  // Trajectory guides and animated motion paths
  for (const m of mapping) {
    const stagger = (m.order / Math.max(1, mapping.length)) * 0.14;
    const normT = clamp((progress - holdStart - stagger) / (moveEnd - holdStart - 0.1));
    const hue = (m.order * 43 + 200) % 360;
    const pathColor = `hsl(${hue}, 92%, 65%)`;

    // Static guide line
    if (normT > 0.01 && normT < 0.99) {
      ctx.save();
      ctx.beginPath();
      const steps = 24;
      for (let s = 0; s <= steps; s++) {
        const pt = computeLetterTransform(m, s / steps, motionStyle, w, h, mapping.length);
        if (s === 0) ctx.moveTo(pt.x, pt.y);
        else ctx.lineTo(pt.x, pt.y);
      }
      ctx.strokeStyle = `hsla(${hue}, 85%, 65%, 0.18)`;
      ctx.lineWidth = 1;
      ctx.stroke();

      ctx.strokeStyle = pathColor;
      ctx.globalAlpha = 0.35;
      ctx.beginPath();
      ctx.arc(m.from.x, m.from.y, 2.5, 0, Math.PI * 2);
      ctx.stroke();
      ctx.beginPath();
      ctx.arc(m.to.x, m.to.y, 2.5, 0, Math.PI * 2);
      ctx.stroke();
      ctx.restore();
    }

    // Active trail trailing the moving letter
    if (normT > 0.005) {
      const trailSpan = 0.45;
      const startT = Math.max(0, normT - trailSpan);
      const subSteps = 16;

      for (let i = 0; i < subSteps; i++) {
        const t1 = startT + (i / subSteps) * (normT - startT);
        const t2 = startT + ((i + 1) / subSteps) * (normT - startT);
        const p1 = computeLetterTransform(m, t1, motionStyle, w, h, mapping.length);
        const p2 = computeLetterTransform(m, t2, motionStyle, w, h, mapping.length);

        const factor = (i + 1) / subSteps;
        ctx.save();
        ctx.beginPath();
        ctx.moveTo(p1.x, p1.y);
        ctx.lineTo(p2.x, p2.y);
        ctx.strokeStyle = pathColor;
        ctx.globalAlpha = factor * 0.85;
        ctx.lineWidth = 1 + factor * 2.5;
        ctx.lineCap = 'round';
        ctx.stroke();
        ctx.restore();
      }
    }
  }

  // Draw Letters along their paths
  for (const m of mapping) {
    const stagger = (m.order / Math.max(1, mapping.length)) * 0.14;
    const normT = clamp((progress - holdStart - stagger) / (moveEnd - holdStart - 0.1));
    const { x, y, rotation, scale, local } = computeLetterTransform(m, normT, motionStyle, w, h, mapping.length);
    const inFlight = normT > 0.02 && normT < 0.98;

    ctx.save();
    ctx.translate(x, y);
    if (rotation !== 0) ctx.rotate(rotation);
    if (scale !== 1) ctx.scale(scale, scale);

    if (inFlight) {
      const hue = (m.order * 43 + 200) % 360;
      ctx.fillStyle = `hsl(${hue}, 95%, 72%)`;
    } else {
      ctx.fillStyle = '#f4f4f5';
    }

    const displayChar = local > 0.6 ? m.to.char : m.from.char;
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';
    ctx.fillText(displayChar, 0, 0);
    ctx.restore();
  }

  if (progress < holdStart) {
    drawPunctuation(src, 1);
  } else {
    drawPunctuation(dst, clamp((progress - 0.78) / 0.18));
  }
}

export function renderMiniCardCanvas(
  progress: number,
  canvas: HTMLCanvasElement,
  source: string,
  target: string,
  motionStyle: MotionStyle = 'arc'
) {
  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  const dpr = typeof window !== 'undefined' ? (window.devicePixelRatio || 1) : 1;
  const w = canvas.width / dpr;
  const h = canvas.height / dpr;

  ctx.save();
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);

  ctx.fillStyle = '#09090b';
  ctx.fillRect(0, 0, w, h);

  const holdStart = 0.08;
  const moveEnd = 0.92;

  const maxW = w - 24;
  let fontSize = 12;
  ctx.font = `bold ${fontSize}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;
  while (fontSize > 8 && (ctx.measureText(source).width > maxW || ctx.measureText(target).width > maxW)) {
    fontSize -= 0.5;
    ctx.font = `bold ${fontSize}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;
  }

  const centerY = h * 0.68;
  const src = computeGlyphLayout(ctx, source, centerY, fontSize, w);
  const dst = computeGlyphLayout(ctx, target, centerY, fontSize, w);

  const buckets: Record<string, Glyph[]> = {};
  src.forEach(g => {
    if (!g.letter) return;
    const k = g.char.toLowerCase();
    if (!buckets[k]) buckets[k] = [];
    buckets[k].push(g);
  });

  const mapping: RenderLetterMapping[] = [];
  const used: Record<string, number> = {};

  dst.forEach(g => {
    if (!g.letter) return;
    const k = g.char.toLowerCase();
    const n = used[k] || 0;
    const s = (buckets[k] || [])[n];
    used[k] = n + 1;
    if (s) {
      mapping.push({
        char: g.char,
        from: { x: s.x, y: s.y, char: s.char, index: s.index },
        to: { x: g.x, y: g.y, char: g.char, index: g.index },
        order: mapping.length,
      });
    }
  });

  // Guide trajectories
  for (const m of mapping) {
    const hue = (m.order * 43 + 200) % 360;

    ctx.save();
    ctx.beginPath();
    const steps = 10;
    for (let s = 0; s <= steps; s++) {
      const normT = s / steps;
      const pt = computeLetterTransform(m, normT, motionStyle, w, h, mapping.length);
      if (s === 0) ctx.moveTo(pt.x, pt.y);
      else ctx.lineTo(pt.x, pt.y);
    }
    ctx.strokeStyle = `hsla(${hue}, 85%, 65%, 0.15)`;
    ctx.lineWidth = 1;
    ctx.stroke();
    ctx.restore();
  }

  // Active letter paths
  for (const m of mapping) {
    const stagger = (m.order / Math.max(1, mapping.length)) * 0.12;
    const normT = clamp((progress - holdStart - stagger) / (moveEnd - holdStart - 0.1));
    const hue = (m.order * 43 + 200) % 360;
    const pathColor = `hsl(${hue}, 92%, 68%)`;

    if (normT > 0.02) {
      const startT = Math.max(0, normT - 0.35);
      const subSteps = 5;
      for (let i = 0; i < subSteps; i++) {
        const t1 = startT + (i / subSteps) * (normT - startT);
        const t2 = startT + ((i + 1) / subSteps) * (normT - startT);

        const p1 = computeLetterTransform(m, t1, motionStyle, w, h, mapping.length);
        const p2 = computeLetterTransform(m, t2, motionStyle, w, h, mapping.length);

        const factor = (i + 1) / subSteps;
        ctx.beginPath();
        ctx.moveTo(p1.x, p1.y);
        ctx.lineTo(p2.x, p2.y);
        ctx.strokeStyle = pathColor;
        ctx.globalAlpha = factor * 0.8;
        ctx.lineWidth = 1 + factor * 1.5;
        ctx.stroke();
      }
    }

    const pt = computeLetterTransform(m, normT, motionStyle, w, h, mapping.length);
    const displayChar = normT < 0.5 ? m.from.char : m.to.char;

    ctx.save();
    ctx.font = `bold ${fontSize}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;
    ctx.fillStyle = pathColor;
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';
    ctx.fillText(displayChar, pt.x, pt.y);
    ctx.restore();
  }

  // Punctuation
  ctx.save();
  ctx.font = `bold ${fontSize}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;
  ctx.fillStyle = '#a1a1aa';
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  if (progress < holdStart) {
    src.forEach(g => {
      if (!g.letter && g.char.trim()) ctx.fillText(g.char, g.x, g.y);
    });
  } else {
    dst.forEach(g => {
      if (!g.letter && g.char.trim()) ctx.fillText(g.char, g.x, g.y);
    });
  }
  ctx.restore();

  ctx.restore();
}

export function renderMultiAnagramCanvas(
  progress: number,
  canvas: HTMLCanvasElement,
  source: string,
  targetPhrases: string[]
) {
  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  const w = canvas.width;
  const h = canvas.height;

  ctx.fillStyle = '#09090b';
  ctx.fillRect(0, 0, w, h);

  if (!source.trim() || targetPhrases.length === 0) return;

  const targets = targetPhrases.slice(0, 5);
  const count = targets.length;

  const sourceY = h * 0.20;
  const maxW = w - 60;
  let sourceFontSize = 18;
  ctx.font = `bold ${sourceFontSize}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;
  while (sourceFontSize > 12 && ctx.measureText(source).width > maxW) {
    sourceFontSize -= 1;
    ctx.font = `bold ${sourceFontSize}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;
  }

  const srcGlyphs = computeGlyphLayout(ctx, source, sourceY, sourceFontSize, w);

  ctx.save();
  ctx.font = `bold ${sourceFontSize}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  ctx.fillStyle = progress < 0.15 ? '#ffffff' : 'rgba(255, 255, 255, 0.45)';
  srcGlyphs.forEach(g => {
    ctx.fillText(g.char, g.x, g.y);
  });
  ctx.restore();

  const colors = [
    { base: 'hsl(150, 85%, 60%)', dim: 'hsla(150, 85%, 60%, 0.2)' },
    { base: 'hsl(190, 90%, 65%)', dim: 'hsla(190, 90%, 65%, 0.2)' },
    { base: 'hsl(280, 85%, 70%)', dim: 'hsla(280, 85%, 70%, 0.2)' },
    { base: 'hsl(340, 85%, 65%)', dim: 'hsla(340, 85%, 65%, 0.2)' },
    { base: 'hsl(40, 90%, 60%)', dim: 'hsla(40, 90%, 60%, 0.2)' },
  ];

  targets.forEach((target, tIdx) => {
    const col = colors[tIdx % colors.length];
    const targetY = h * 0.52 + (tIdx * ((h * 0.38) / Math.max(1, count - 1)));
    const tFontSize = Math.min(13, Math.max(10, Math.floor(130 / Math.max(1, count))));
    ctx.font = `600 ${tFontSize}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;

    const dstGlyphs = computeGlyphLayout(ctx, target, targetY, tFontSize, w);

    const buckets: Record<string, Glyph[]> = {};
    srcGlyphs.forEach(g => {
      if (!g.letter) return;
      const k = g.char.toLowerCase();
      if (!buckets[k]) buckets[k] = [];
      buckets[k].push(g);
    });

    const used: Record<string, number> = {};
    const mapping: RenderLetterMapping[] = [];

    dstGlyphs.forEach(g => {
      if (!g.letter) return;
      const k = g.char.toLowerCase();
      const n = used[k] || 0;
      const s = (buckets[k] || [])[n];
      used[k] = n + 1;
      if (s) {
        mapping.push({
          char: g.char,
          from: { x: s.x, y: s.y, char: s.char, index: s.index },
          to: { x: g.x, y: g.y, char: g.char, index: g.index },
          order: mapping.length,
        });
      }
    });

    for (const m of mapping) {
      ctx.save();
      ctx.beginPath();
      const steps = 12;
      for (let s = 0; s <= steps; s++) {
        const normT = s / steps;
        const local = smoother(normT);
        const x = m.from.x + (m.to.x - m.from.x) * local;
        const curveOffset = Math.sin(normT * Math.PI) * (20 + (tIdx - 2) * 12);
        const y = m.from.y + (m.to.y - m.from.y) * local + curveOffset;
        if (s === 0) ctx.moveTo(x, y);
        else ctx.lineTo(x, y);
      }
      ctx.strokeStyle = col.dim;
      ctx.lineWidth = 1;
      ctx.stroke();
      ctx.restore();

      const stagger = (m.order / Math.max(1, mapping.length)) * 0.12;
      const normT = clamp((progress - 0.08 - stagger) / 0.82);

      if (normT > 0.01) {
        const local = smoother(normT);
        const curveOffset = Math.sin(normT * Math.PI) * (20 + (tIdx - 2) * 12);
        const px = m.from.x + (m.to.x - m.from.x) * local;
        const py = m.from.y + (m.to.y - m.from.y) * local + curveOffset;

        ctx.save();
        ctx.fillStyle = col.base;
        ctx.beginPath();
        ctx.arc(px, py, 2.5, 0, Math.PI * 2);
        ctx.fill();

        if (normT > 0.15 && normT < 0.95) {
          ctx.font = `bold 10px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;
          ctx.textAlign = 'center';
          ctx.textBaseline = 'bottom';
          ctx.fillText(m.char, px, py - 3);
        }
        ctx.restore();
      }
    }

    ctx.save();
    ctx.font = `600 ${tFontSize}px Inter, -apple-system, BlinkMacSystemFont, sans-serif`;
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';
    ctx.fillStyle = progress > 0.8 ? col.base : 'rgba(244, 244, 245, 0.65)';
    dstGlyphs.forEach(g => {
      ctx.fillText(g.char, g.x, g.y);
    });
    ctx.restore();
  });
}




