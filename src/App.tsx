/**
 * Robust Part of Speech Classifier
 * Identifies Noun, Adjective, Verb, Adverb, Pronoun, Prep, Art, Conj
 */
export function classifyWordPOS(rawWord: string): WordPartOfSpeech {
  const w = rawWord.toLowerCase().trim();
  if (!w) return 'other';

  if (PRONOUNS.has(w)) return 'pron';
  if (ARTICLES.has(w)) return 'art';
  if (AUX.has(w)) return 'verb';
  if (PREPS.has(w)) return 'prep';
  if (CONJS.has(w)) return 'conj';
  if (ADJECTIVES.has(w)) return 'adj';
  if (VERBS.has(w)) return 'verb';
  if (ADVERBS.has(w)) return 'adv';
  if (NOUNS.has(w)) return 'noun';

  // Morphological rules
  if (w.endsWith('ly') && w.length > 3) return 'adv';
  if (
    (w.endsWith('ous') ||
      w.endsWith('ful') ||
      w.endsWith('able') ||
      w.endsWith('ible') ||
      w.endsWith('ish') ||
      w.endsWith('ive') ||
      w.endsWith('ic') ||
      w.endsWith('al') ||
      w.endsWith('less')) &&
    w.length > 4
  ) {
    return 'adj';
  }

  if (
    (w.endsWith('tion') ||
      w.endsWith('sion') ||
      w.endsWith('ment') ||
      w.endsWith('ness') ||
      w.endsWith('ity') ||
      w.endsWith('ance') ||
      w.endsWith('ence') ||
      w.endsWith('ist') ||
      w.endsWith('ism') ||
      w.endsWith('ship') ||
      w.endsWith('hood') ||
      w.endsWith('dom') ||
      w.endsWith('er') ||
      w.endsWith('or')) &&
    w.length > 3
  ) {
    return 'noun';
  }

  if (
    (w.endsWith('ize') ||
      w.endsWith('ise') ||
      w.endsWith('ate') ||
      w.endsWith('ify') ||
      w.endsWith('ed') ||
      w.endsWith('ing')) &&
    w.length > 3
  ) {
    return 'verb';
  }

  // Fallback heuristic: 3+ chars default to noun in word combinations
  if (w.length >= 3) return 'noun';

  return 'other';
}

export function getWordWithPOS(rawWord: string): WordWithPOS {
  const pos = classifyWordPOS(rawWord);
  const posLabel = POS_BADGES[pos]?.label || 'WORD';
  return {
    word: rawWord,
    pos,
    posLabel,
  };
}

