/**
 * Detects grammatical phrase patterns like "Adjective + Noun", "Sentence (Subject + Verb + Object)", etc.
 */
export function detectGrammarPattern(words: string[]): {
  pattern: string;
  hasNoun: boolean;
  hasAdj: boolean;
  hasVerb: boolean;
  hasAdv: boolean;
  wordsWithPOS: WordWithPOS[];
} {
  const tagged = words.map(getWordWithPOS);
  const poses = tagged.map(t => t.pos);

  const hasNoun = poses.some(p => p === 'noun');
  const hasAdj = poses.some(p => p === 'adj');
  const hasVerb = poses.some(p => p === 'verb');
  const hasAdv = poses.some(p => p === 'adv');

  let pattern = 'Word Combination';

  if (poses.length === 2) {
    if (poses[0] === 'adj' && poses[1] === 'noun') {
      pattern = 'Adjective + Noun';
    } else if (poses[0] === 'verb' && poses[1] === 'noun') {
      pattern = 'Verb + Noun';
    } else if (poses[0] === 'noun' && poses[1] === 'verb') {
      pattern = 'Noun + Verb';
    } else if (poses[0] === 'noun' && poses[1] === 'noun') {
      pattern = 'Compound Noun';
    } else if (poses[0] === 'adv' && (poses[1] === 'adj' || poses[1] === 'verb')) {
      pattern = 'Adverb + Action/Description';
    }
  } else if (poses.length === 3) {
    if (poses[0] === 'adj' && poses[1] === 'adj' && poses[2] === 'noun') {
      pattern = 'Adjectives + Noun';
    } else if (poses[0] === 'adj' && poses[1] === 'noun' && poses[2] === 'noun') {
      pattern = 'Adjective + Noun Phrase';
    } else if ((poses[0] === 'noun' || poses[0] === 'pron') && poses[1] === 'verb' && poses[2] === 'noun') {
      pattern = 'Sentence (S-V-O)';
    } else if (poses[0] === 'verb' && poses[1] === 'art' && poses[2] === 'noun') {
      pattern = 'Verb Phrase (Action + Object)';
    } else if (poses[0] === 'art' && poses[1] === 'adj' && poses[2] === 'noun') {
      pattern = 'Descriptive Noun Phrase';
    }
  } else if (poses.length >= 4) {
    if ((poses.includes('pron') || poses.includes('noun')) && poses.includes('verb')) {
      pattern = 'Complete Sentence';
    } else if (hasAdj && hasNoun) {
      pattern = 'Descriptive Phrase';
    } else if (hasVerb) {
      pattern = 'Action Phrase';
    }
  } else if (hasAdj && hasNoun) {
    pattern = 'Adjective & Noun';
  } else if (hasVerb) {
    pattern = 'Action Phrase';
  } else if (hasNoun) {
    pattern = 'Noun Phrase';
  }

  return {
    pattern,
    hasNoun,
    hasAdj,
    hasVerb,
    hasAdv,
    wordsWithPOS: tagged,
  };
}




