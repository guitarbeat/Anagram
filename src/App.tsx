// Active in-memory map of Urban Dictionary words
export const URBAN_WORD_MAP = new Map<string, UrbanLexiconItem>();

for (const item of INITIAL_URBAN_WORDS) {
  URBAN_WORD_MAP.set(item.word.toLowerCase(), item);
}

/**
 * Checks if a word is in the Urban Dictionary lexicon
 */
export function isUrbanWord(word: string): boolean {
  return URBAN_WORD_MAP.has(word.toLowerCase().trim());
}

/**
 * Gets details for an Urban Dictionary word
 */
export function getUrbanWordDetails(word: string): UrbanLexiconItem | undefined {
  return URBAN_WORD_MAP.get(word.toLowerCase().trim());
}

/**
 * Returns all currently registered Urban Dictionary words
 */
export function getAllUrbanWords(): UrbanLexiconItem[] {
  return Array.from(URBAN_WORD_MAP.values());
}

/**
 * Dynamically ingests words fetched from unofficialurbandictionaryapi.com
 */
export function ingestUrbanWords(
  items: Array<{ word: string; meaning?: string; pos?: WordPartOfSpeech; f?: number }>
): number {
  let addedCount = 0;
  for (const it of items) {
    const clean = it.word.toLowerCase().replace(/[^a-z]/g, '');
    if (clean.length >= 2 && clean.length <= 16 && !URBAN_WORD_MAP.has(clean)) {
      const newItem: UrbanLexiconItem = {
        word: clean,
        pos: it.pos || 'noun',
        f: it.f || 1800000,
        shortMeaning: it.meaning?.slice(0, 120),
      };
      URBAN_WORD_MAP.set(clean, newItem);
      addedCount++;
    }
  }
  return addedCount;
}


