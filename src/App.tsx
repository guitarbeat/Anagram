// High-frequency multilingual dictionary entries with frequency scores
export interface MultilingualEntry {
  w: string;
  f: number;
  r: number;
  lang: LanguageCode;
  pos: WordPartOfSpeech;
}

// Build pre-indexed lists for fast access
function createLangEntries(
  words: { [word: string]: { f: number; pos: WordPartOfSpeech } },
  lang: LanguageCode
): MultilingualEntry[] {
  let rank = 100;
  return Object.entries(words).map(([w, data]) => ({
    w: stripAccents(w.toLowerCase()),
    f: data.f,
    r: rank++,
    lang,
    pos: data.pos,
  }));
}

