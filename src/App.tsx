export const SolverSection: React.FC<SolverSectionProps> = ({
  sourceText,
  results,
  isSolving,
  metrics,
  activeTargetPhrase,
  progress = 0,
  motionStyle = 'arc',
  onAnimatePhrase,
  onShowToast,
}) => {
  const [copiedIndex, setCopiedIndex] = useState<number | null>(null);
  const [showPaths, setShowPaths] = useState<boolean>(false);
  const [wordFilter, setWordFilter] = useState<'all' | '2' | '3' | '4+'>('all');
  const [searchQuery, setSearchQuery] = useState<string>('');
  const [sortBy, setSortBy] = useState<'score' | 'words_asc' | 'words_desc' | 'alpha'>('score');

  const copyToClipboard = (text: string) => {
    if (navigator?.clipboard?.writeText) {
      navigator.clipboard.writeText(text).catch(() => {
        const textarea = document.createElement('textarea');
        textarea.value = text;
        document.body.appendChild(textarea);
        textarea.select();
        document.execCommand('copy');
        document.body.removeChild(textarea);
      });
    } else {
      const textarea = document.createElement('textarea');
      textarea.value = text;
      document.body.appendChild(textarea);
      textarea.select();
      document.execCommand('copy');
      document.body.removeChild(textarea);
    }
  };

  const handleCopyPhrase = (phrase: string, idx: number) => {
    copyToClipboard(phrase);
    setCopiedIndex(idx);
    onShowToast(`Copied "${phrase}"`);
    setTimeout(() => setCopiedIndex(null), 2000);
  };

  // Filter & sort results
  const filteredResults = useMemo(() => {
    let list = [...results];

    // Word count filter
    if (wordFilter === '2') {
      list = list.filter(r => r.words.length === 2);
    } else if (wordFilter === '3') {
      list = list.filter(r => r.words.length === 3);
    } else if (wordFilter === '4+') {
      list = list.filter(r => r.words.length >= 4);
    }

    // Search query filter
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase().trim();
      list = list.filter(r => r.phrase.toLowerCase().includes(q));
    }

    // Sort
    if (sortBy === 'words_asc') {
      list.sort((a, b) => a.words.length - b.words.length || b.score - a.score);
    } else if (sortBy === 'words_desc') {
      list.sort((a, b) => b.words.length - a.words.length || b.score - a.score);
    } else if (sortBy === 'alpha') {
      list.sort((a, b) => a.phrase.localeCompare(b.phrase));
    }

    return list;
  }, [results, wordFilter, searchQuery, sortBy]);

  return (
    <div className="space-y-3.5">
      {/* Filters and Controls Toolbar */}
      <div className="flex items-center justify-between gap-3 text-xs flex-wrap px-1">
        <div className="flex items-center gap-2">
          <span className="font-mono text-[#f4f4f5] font-semibold text-sm">
            Discovered Anagrams
          </span>
          <span className="font-mono text-xs text-[#71717a] bg-[#18181b] px-2 py-0.5 rounded border border-[#27272a]">
            {filteredResults.length} {filteredResults.length !== results.length ? `of ${results.length}` : ''}
          </span>
          {metrics && (
            <span className="font-mono text-[11px] text-[#52525b] tabular-nums hidden sm:inline-block">
              · {metrics.elapsedMs.toFixed(0)}ms
            </span>
          )}
        </div>

        {results.length > 0 && (
          <div className="flex items-center gap-2 flex-wrap">
            {/* Search within results */}
            <div className="relative">
              <input
                type="text"
                value={searchQuery}
                onChange={e => setSearchQuery(e.target.value)}
                placeholder="Filter word..."
                className="w-28 sm:w-36 bg-[#121214] border border-[#27272a] focus:border-[#52525b] rounded px-2 py-1 text-[11px] font-mono text-[#f4f4f5] placeholder-[#52525b] focus:outline-none transition-colors"
              />
              {searchQuery && (
                <button
                  type="button"
                  onClick={() => setSearchQuery('')}
                  aria-label="Clear word search filter"
                  className="absolute right-1.5 top-1/2 -translate-y-1/2 text-[#71717a] hover:text-[#f4f4f5] p-0.5 cursor-pointer"
                >
                  <X className="w-3 h-3" />
                </button>
              )}
            </div>

            {/* Word length filter tabs */}
            <div className="flex items-center bg-[#121214] p-0.5 rounded border border-[#27272a]">
              {(['all', '2', '3', '4+'] as const).map(tab => (
                <button
                  key={tab}
                  type="button"
                  onClick={() => setWordFilter(tab)}
                  className={`px-2 py-0.5 rounded text-[10px] font-mono uppercase transition-colors cursor-pointer ${
                    wordFilter === tab
                      ? 'bg-[#27272a] text-[#f4f4f5] font-medium'
                      : 'text-[#71717a] hover:text-[#f4f4f5]'
                  }`}
                >
                  {tab === 'all' ? 'All' : `${tab}w`}
                </button>
              ))}
            </div>

            {/* Sort selector */}
            <select
              value={sortBy}
              onChange={e => setSortBy(e.target.value as any)}
              className="bg-[#121214] border border-[#27272a] text-[#a1a1aa] rounded px-2 py-1 text-[11px] font-mono focus:outline-none cursor-pointer"
            >
              <option value="score">Best Flow</option>
              <option value="words_asc">Fewest Words</option>
              <option value="words_desc">Most Words</option>
              <option value="alpha">A &rarr; Z</option>
            </select>

            <button
              type="button"
              onClick={() => setShowPaths(!showPaths)}
              className={`font-mono text-xs px-2 py-1 rounded border transition-colors cursor-pointer ${
                showPaths
                  ? 'bg-emerald-950/40 border-emerald-600/50 text-emerald-400'
                  : 'bg-[#121214] border-[#27272a] text-[#71717a] hover:text-[#f4f4f5]'
              }`}
              title="Show mini path animated canvases on each card"
            >
              {showPaths ? 'Paths On' : 'Paths Off'}
            </button>
          </div>
        )}
      </div>

      {/* Results View */}
      {isSolving ? (
        <div className="border border-[#27272a] rounded-xl p-12 text-center space-y-3 bg-[#121214]">
          <div className="inline-block w-5 h-5 border-2 border-emerald-400 border-t-transparent rounded-full animate-spin" />
          <p className="text-xs text-[#a1a1aa] font-mono">Searching permutations across lexicon...</p>
        </div>
      ) : filteredResults.length === 0 ? (
        <div className="border border-[#27272a] rounded-xl p-10 text-center space-y-2 bg-[#121214]">
          <p className="text-sm text-[#f4f4f5] font-mono font-medium">
            {sourceText.trim()
              ? 'No exact multi-word anagrams found for this filter.'
              : 'Enter a name or phrase above to discover anagrams.'}
          </p>
          {sourceText.trim() && (
            <p className="text-xs text-[#71717a] font-mono">
              Try entering additional words or a full name.
            </p>
          )}
        </div>
      ) : (
        <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 gap-3 max-h-[660px] overflow-y-auto pr-0.5">
          {filteredResults.map((item, idx) => (
            <AnagramResultCard
              key={`${item.phrase}_${idx}`}
              item={item}
              idx={idx}
              sourceText={sourceText}
              progress={progress}
              motionStyle={motionStyle}
              showMiniPath={showPaths}
              isActive={item.phrase.toLowerCase() === activeTargetPhrase?.toLowerCase()}
              onAnimatePhrase={onAnimatePhrase}
              onCopy={handleCopyPhrase}
              isCopied={copiedIndex === idx}
            />
          ))}
        </div>
      )}
    </div>
  );
};

// ----------------------------------------------------
// MAIN APP COMPONENT
// ----------------------------------------------------
export default function App() {
  const [sourceName, setSourceName] = useState<string>('Aaron Lorenzo Woods');
  const [targetPhrase, setTargetPhrase] = useState<string>('Zoolander owns a roo');

  const [isPlaying, setIsPlaying] = useState<boolean>(true);
  const [progress, setProgress] = useState<number>(0);
  const [motionStyle, setMotionStyle] = useState<MotionStyle>('arc');
  const [speed, setSpeed] = useState<number>(1);

  const [results, setResults] = useState<AnagramResult[]>([]);
  const [metrics, setMetrics] = useState<SolveMetrics | null>(null);
  const [isSolving, setIsSolving] = useState<boolean>(false);

  const [toasts, setToasts] = useState<ToastMessage[]>([]);

  const showToast = useCallback((text: string) => {
    const id = Math.random().toString(36).slice(2);
    setToasts(prev => [...prev.slice(-2), { id, text }]);
    setTimeout(() => {
      setToasts(prev => prev.filter(t => t.id !== id));
    }, 2800);
  }, []);

  useEffect(() => {
    if (typeof window !== 'undefined') {
      const params = new URLSearchParams(window.location.search);
      const urlSource = params.get('q') || params.get('source');
      const urlTarget = params.get('t') || params.get('target');
      if (urlSource) setSourceName(urlSource);
      if (urlTarget) {
        setTargetPhrase(urlTarget);
      }
    }
  }, []);

  useEffect(() => {
    if (!sourceName.trim()) {
      setResults([]);
      setMetrics(null);
      return;
    }

    setIsSolving(true);
    let isCancelled = false;

    const timer = setTimeout(async () => {
      try {
        const solved = await solveAnagrams({
          source: sourceName,
          depth: 50000,
          resultLimit: 80,
        });

        if (!isCancelled) {
          setResults(solved.results);
          setMetrics(solved.metrics);

          const isCurrentExact = exact(sourceName, targetPhrase);
          if (!isCurrentExact) {
            if (solved.results.length > 0) {
              setTargetPhrase(solved.results[0].phrase);
            } else {
              setTargetPhrase('');
            }
          }
        }
      } catch (err) {
        console.error('Anagram solve error:', err);
      } finally {
        if (!isCancelled) {
          setIsSolving(false);
        }
      }
    }, 200);

    return () => {
      isCancelled = true;
      clearTimeout(timer);
    };
  }, [sourceName]);

  const handleAnimatePhrase = (phrase: string) => {
    setTargetPhrase(phrase);
    window.scrollTo({ top: 0, behavior: 'smooth' });
  };

  return (
    <div className="min-h-[100dvh] bg-[#09090b] text-[#f4f4f5] flex flex-col selection:bg-emerald-900/60 selection:text-emerald-200 antialiased font-sans">
      {/* Toast Notification Container */}
      <div className="fixed bottom-5 right-5 z-50 flex flex-col gap-2 pointer-events-none">
        {toasts.map(t => (
          <div
            key={t.id}
            className="bg-[#18181b] border border-emerald-500/40 text-[#f4f4f5] px-4 py-2.5 rounded-lg shadow-2xl text-xs font-mono flex items-center gap-2 animate-in fade-in slide-in-from-bottom-3 duration-200"
          >
            <Check className="w-3.5 h-3.5 text-emerald-400 shrink-0" />
            <span>{t.text}</span>
          </div>
        ))}
      </div>

      {/* Main Container */}
      <main className="flex-1 max-w-4xl w-full mx-auto px-4 sm:px-6 py-6 space-y-6">
        {/* Input & Analytics Header */}
        <section aria-label="Input search" className="space-y-3">
          {/* Clean Input Box */}
          <div className="relative">
            <input
              id="source-input"
              type="text"
              value={sourceName}
              onChange={e => setSourceName(e.target.value)}
              placeholder="Enter name or phrase to solve (e.g. William Shakespeare)..."
              className="w-full bg-[#121214] border border-[#27272a] focus:border-emerald-500/60 rounded-xl px-4 py-3 text-sm sm:text-base font-mono text-[#f4f4f5] placeholder-[#52525b] focus:outline-none transition-colors shadow-inner"
            />
            {sourceName && (
              <button
                type="button"
                onClick={() => {
                  setSourceName('');
                  setTargetPhrase('');
                }}
                aria-label="Clear input"
                className="absolute right-3.5 top-1/2 -translate-y-1/2 text-[#71717a] hover:text-[#f4f4f5] p-1 rounded-md hover:bg-[#27272a] cursor-pointer transition-colors"
              >
                <X className="w-4 h-4" />
              </button>
            )}
          </div>
        </section>

        {/* Discovered Anagrams Section */}
        <section aria-label="Anagram Results Grid">
          <SolverSection
            sourceText={sourceName}
            results={results}
            isSolving={isSolving}
            metrics={metrics}
            activeTargetPhrase={targetPhrase}
            progress={progress}
            motionStyle={motionStyle}
            onAnimatePhrase={handleAnimatePhrase}
            onShowToast={showToast}
          />
        </section>
      </main>
    </div>
  );
}
