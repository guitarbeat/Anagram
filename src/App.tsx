/**
 * Normalizes diacritics and accented characters common in European languages
 * so names and foreign phrases match accurately against standard letter counts.
 */
export function stripAccents(str: string): string {
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/ß/g, 'ss')
    .replace(/æ/g, 'ae')
    .replace(/œ/g, 'oe');
}

