/**
 * Detects the dominant language and grammatical pattern of a phrase
 */
export function analyzeMultilingualPhrase(
  words: string[],
  selectedLang: LanguageCode = 'all'
): {
  language: LanguageCode;
  pattern: string;
  hasNoun: boolean;
  hasAdj: boolean;
  hasVerb: boolean;
  hasAdv: boolean;
  wordsWithPOS: WordWithPOS[];
  fluencyBonus: number;
} {
  const langVotes: Record<LanguageCode, number> = { all: 0, en: 0, es: 0, fr: 0, de: 0, it: 0, la: 0 };
  const taggedWords: WordWithPOS[] = [];

  for (const w of words) {
    const norm = stripAccents(w.toLowerCase());
    const info = classifyMultilingualPOS(norm, selectedLang);
    const lang = info.lang;
    langVotes[lang] = (langVotes[lang] || 0) + 1;

    let label = 'WORD';
    if (info.pos === 'noun') label = 'NOUN';
    else if (info.pos === 'adj') label = 'ADJ';
    else if (info.pos === 'verb') label = 'VERB';
    else if (info.pos === 'adv') label = 'ADV';
    else if (info.pos === 'art') label = 'ART';
    else if (info.pos === 'prep') label = 'PREP';
    else if (info.pos === 'pron') label = 'PRON';
    else if (info.pos === 'conj') label = 'CONJ';

    taggedWords.push({
      word: w,
      pos: info.pos,
      posLabel: label,
      language: lang,
    });
  }

  // Determine dominant language
  let dominantLang: LanguageCode = 'en';
  let maxVotes = 0;
  for (const [code, votes] of Object.entries(langVotes)) {
    if (code !== 'all' && votes > maxVotes) {
      maxVotes = votes;
      dominantLang = code as LanguageCode;
    }
  }

  if (selectedLang !== 'all' && selectedLang !== 'en') {
    dominantLang = selectedLang;
  }

  const hasNoun = taggedWords.some(t => t.pos === 'noun');
  const hasAdj = taggedWords.some(t => t.pos === 'adj');
  const hasVerb = taggedWords.some(t => t.pos === 'verb');
  const hasAdv = taggedWords.some(t => t.pos === 'adv');
  const hasArt = taggedWords.some(t => t.pos === 'art');

  let pattern = 'Word Combination';
  let fluencyBonus = 0;

  // Language-specific natural phrasing detection
  if (dominantLang === 'es') {
    if (hasArt && hasNoun && hasAdj) {
      pattern = 'Frase Descriptiva (Art + N + Adj)';
      fluencyBonus = 8.5;
    } else if (hasNoun && hasAdj) {
      pattern = 'Sustantivo + Adjetivo';
      fluencyBonus = 7.0;
    } else if (hasNoun && hasVerb) {
      pattern = 'Sujeto + Acción';
      fluencyBonus = 7.5;
    } else if (hasAdj && hasNoun) {
      pattern = 'Adjetivo + Sustantivo';
      fluencyBonus = 6.5;
    }
  } else if (dominantLang === 'fr') {
    if (hasArt && hasNoun && hasAdj) {
      pattern = 'Syntagme (Art + Nom + Adj)';
      fluencyBonus = 8.5;
    } else if (hasNoun && hasAdj) {
      pattern = 'Nom + Adjectif';
      fluencyBonus = 7.5;
    } else if (hasNoun && hasVerb) {
      pattern = 'Sujet + Verbe';
      fluencyBonus = 7.0;
    } else if (hasAdj && hasNoun) {
      pattern = 'Adjectif + Nom';
      fluencyBonus = 6.5;
    }
  } else if (dominantLang === 'de') {
    if (hasArt && hasAdj && hasNoun) {
      pattern = 'Nominalphrase (Art + Adj + Nomen)';
      fluencyBonus = 8.5;
    } else if (hasAdj && hasNoun) {
      pattern = 'Adjektiv + Nomen';
      fluencyBonus = 7.0;
    } else if (hasNoun && hasVerb) {
      pattern = 'Subjekt + Verb';
      fluencyBonus = 7.5;
    }
  } else if (dominantLang === 'it') {
    if (hasArt && hasNoun && hasAdj) {
      pattern = 'Frase Descrittiva';
      fluencyBonus = 8.5;
    } else if (hasNoun && hasAdj) {
      pattern = 'Sostantivo + Aggettivo';
      fluencyBonus = 7.5;
    } else if (hasNoun && hasVerb) {
      pattern = 'Soggetto + Verbo';
      fluencyBonus = 7.0;
    }
  } else if (dominantLang === 'la') {
    if (hasNoun && hasAdj) {
      pattern = 'Nomen + Adiectivum';
      fluencyBonus = 8.0;
    } else if (hasNoun && hasVerb) {
      pattern = 'Sententia Latina';
      fluencyBonus = 8.5;
    } else if (hasAdj && hasNoun) {
      pattern = 'Dictum Classicum';
      fluencyBonus = 7.5;
    }
  } else {
    // English default
    if (hasAdj && hasNoun) {
      pattern = 'Adjective + Noun';
      fluencyBonus = 6.5;
    } else if (hasNoun && hasVerb) {
      pattern = 'Sentence (S-V-O)';
      fluencyBonus = 7.0;
    }
  }

  return {
    language: dominantLang,
    pattern,
    hasNoun,
    hasAdj,
    hasVerb,
    hasAdv,
    wordsWithPOS: taggedWords,
    fluencyBonus,
  };
}

